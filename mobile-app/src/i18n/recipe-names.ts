export function recipeName(name: string, language: 'en' | 'ar'): string {
  return language === 'ar' ? arabicRecipeNames[name.normalize('NFKC').trim().replace(/\s+/g, ' ').toLowerCase()] ?? name : name;
}

export function recipeNameMatches(name: string, query: string, language: 'en' | 'ar'): boolean {
  const needle = query.trim().toLocaleLowerCase();
  return name.toLocaleLowerCase().includes(needle) || recipeName(name, language).toLocaleLowerCase().includes(needle);
}
