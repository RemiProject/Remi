# Imports the reviewed Remi v3 food photography into the app bundle.
# Usage: python3 scripts/import-food-images.py <handoff folder with image-map.json, manifest.json, images/, catalogue/>
# Needs Pillow (with WebP). Re-run after the handoff gains images: it rewrites src/data/food-images.ts, writes only the
# photos whose source changed (assets/food/sources.json records each source's SHA-256) and removes photos no longer mapped.
#
# Recipes: recipe_key -> name through catalogue/recipes.csv (the backend importer upserts global recipes by
# lower(name), so the catalogue name is the stable link the app can see). Ingredients: exact foods.csv name, its
# Arabic name and its listed aliases; an exact name always wins over another food's alias.
import csv, hashlib, io, json, sys, unicodedata
from pathlib import Path
from PIL import Image

src = Path(sys.argv[1]); app = Path(__file__).resolve().parent.parent
out = app / 'assets' / 'food'; ts = app / 'src' / 'data' / 'food-images.ts'; record_path = out / 'sources.json'
SIZES = {'recipe': 800, 'ingredient': 256}  # card/hero width on a 3x phone vs. a 64 pt kitchen thumbnail
REVIEWED = {'generated_reviewed', 'sourced_reviewed'}

def rows(name):
    with open(src / 'catalogue' / name, encoding='utf-8-sig') as f:
        return list(csv.DictReader(line for line in f if not line.startswith('#')))
key = lambda s: ' '.join(unicodedata.normalize('NFKC', s).split()).lower()

recipes = {r['recipe_key']: r for r in rows('recipes.csv')}
foods = {r['name']: r for r in rows('foods.csv')}
manifest = {(e['kind'], e['key']): e for e in json.load(open(src / 'manifest.json'))}
entries = [e for e in json.load(open(src / 'image-map.json'))['images'] if e['status'] in REVIEWED and e['target_path']]

record = json.loads(record_path.read_text()) if record_path.exists() else {}
kept, written, changed = set(), [], []
recipe_map, names, aliases, credits = {}, {}, {}, []
for e in entries:
    kind, k = e['kind'], e['key']; path = src / e['target_path']
    data = path.read_bytes(); expected = manifest[(kind, k)]['sha256']
    if hashlib.sha256(data).hexdigest() != expected: sys.exit(f'sha256 mismatch: {path}')
    slug = Path(e['target_path']).stem; rel = f'{kind}s/{slug}.webp'; dest = out / rel; dest.parent.mkdir(parents=True, exist_ok=True)
    kept.add(rel)
    if record.get(rel) == expected and dest.exists(): pass  # same source photo: keep the file as it is
    else:
        img = Image.open(path).convert('RGB'); w, h = img.size; s = min(w, h)
        img = img.crop(((w - s) // 2, (h - s) // 2, (w - s) // 2 + s, (h - s) // 2 + s))  # centred square, never upscaled
        size = min(SIZES[kind], s); buf = io.BytesIO()
        img.resize((size, size), Image.LANCZOS).save(buf, 'WEBP', quality=72 if kind == 'recipe' else 75, method=6)
        # No record yet (first run with one): an identical existing file is unchanged, anything else is new or replaced.
        if not (dest.exists() and dest.read_bytes() == buf.getvalue()):
            (changed if dest.exists() else written).append(rel); dest.write_bytes(buf.getvalue())
        record[rel] = expected
    req = f"require('../../assets/food/{kind}s/{slug}.webp')"
    if kind == 'recipe':
        recipe_map[key(recipes[k]['name'])] = req
    else:
        f = foods[k]; names[key(f['name'])] = req
        for alias in [f['name_ar'], *f['aliases_ar'].split('|'), *f['aliases_en'].split('|')]:
            if alias.strip(): aliases.setdefault(key(alias), req)
    m = manifest[(kind, k)]
    if m['origin'] == 'sourced':
        c = m['source_candidate']; credits.append({'subject': e['name'], 'title': c['title'], 'author': c['author'], 'license': c['license'], 'licenseUrl': c['licenseUrl'], 'sourceUrl': c['sourceUrl']})

removed = sorted(str(p.relative_to(out)) for p in out.rglob('*.webp') if str(p.relative_to(out)) not in kept)
for rel in removed: (out / rel).unlink()
record_path.write_text(json.dumps({k: record[k] for k in sorted(kept)}, indent=1) + '\n')
ingredient_map = {**{a: r for a, r in aliases.items() if a not in names}, **names}
missing = [k for k in recipes if key(recipes[k]['name']) not in recipe_map]
lines = ['// Generated by scripts/import-food-images.py from the Remi v3 image handoff. Do not edit by hand.',
         '/** Finished-dish photos, keyed by the lower-cased catalogue recipe name. */',
         'export const recipeImages: Readonly<Record<string, number>> = {',
         *[f'  {json.dumps(n, ensure_ascii=False)}: {r},' for n, r in sorted(recipe_map.items())], '};',
         '/** Ingredient photos, keyed by lower-cased catalogue food name, Arabic name and aliases. */',
         'export const ingredientImages: Readonly<Record<string, number>> = {',
         *[f'  {json.dumps(n, ensure_ascii=False)}: {r},' for n, r in sorted(ingredient_map.items())], '};',
         '/** Photos from outside sources. Every other food photo is AI generated. */',
         f'export const sourcedImageCredits = {json.dumps(credits, ensure_ascii=False, indent=2)} as const;', '']
ts.write_text('\n'.join(lines), encoding='utf-8')
size = sum(p.stat().st_size for p in out.rglob('*.webp'))
print(f'{len(recipe_map)} recipes ({len(missing)} without a photo), {len(names)} ingredients, {len(ingredient_map)} lookup keys, '
      f'{len(credits)} sourced, {size / 1e6:.1f} MB; {len(written)} new, {len(changed)} replaced, {len(removed)} removed, '
      f'{len(kept) - len(written) - len(changed)} unchanged')
for label, items in (('replaced', changed), ('removed', removed)):
    for rel in items: print(f'  {label}: {rel}')
