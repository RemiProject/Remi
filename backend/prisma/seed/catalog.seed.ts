const url = process.env.DATABASE_URL_MIGRATOR || process.env.DATABASE_URL;
if (!url) throw new Error('DATABASE_URL is required');
const client = new pg.Client({ connectionString: url });
await client.connect();
try {
  await client.query('BEGIN');
  const categories = new Map((await client.query('SELECT id, code FROM "FoodCategory"')).rows.map((row) => [row.code, row.id]));
  const languageRows = await client.query('SELECT id, code FROM "Language" WHERE code IN (\'ar\', \'en\')');
  const languages = new Map(languageRows.rows.map((row) => [row.code, row.id]));
  for (const [categoryCode, names] of Object.entries(groups)) {
    const categoryId = categories.get(categoryCode);
    if (!categoryId) throw new Error(`FoodCategory ${categoryCode} must be seeded first`);
    for (const name of names.split('|')) {
      const settings = unitSettings[name] ?? { unit: 'GRAM' as const };
      const saved = await client.query(
        'INSERT INTO "Food" ("id", "categoryId", "name", "defaultUnit", "gramsPerPiece", "densityGPerMl") VALUES ($1, $2, $3, $4::"Unit", $5, $6) ON CONFLICT (lower("name")) DO UPDATE SET "categoryId" = EXCLUDED."categoryId", "defaultUnit" = EXCLUDED."defaultUnit", "gramsPerPiece" = EXCLUDED."gramsPerPiece", "densityGPerMl" = EXCLUDED."densityGPerMl", "updatedAt" = now() RETURNING "id"',
        [uuidv7(), categoryId, name, settings.unit, settings.gramsPerPiece ?? null, settings.densityGPerMl ?? null],
      );
      const foodId = saved.rows[0].id as string;
      const localizedName = arabic[name];
      if (localizedName && languages.has('ar')) {
        await client.query('INSERT INTO "FoodAlias" ("id", "foodId", "languageId", "alias", "isPrimary") VALUES ($1, $2, $3, $4, true) ON CONFLICT DO NOTHING', [uuidv7(), foodId, languages.get('ar'), localizedName]);
      }
    }
  }
  await client.query('COMMIT');
  console.log(`catalog seed done (${Object.values(groups).flatMap((x) => x.split('|')).length} food names; nutrient profiles intentionally absent)`);
} catch (error) {
  await client.query('ROLLBACK');
  throw error;
} finally {
  await client.end();
}
